def write_companies(frame):
    missing = [item[0] for item in COMPANIES if item[0] not in frame.index]
    if missing:
        raise SystemExit(f"missing codes: {missing}")
    if len(COMPANIES) != 50:
        raise SystemExit(f"expected 50 companies, got {len(COMPANIES)}")
    COMPANY_DIR.mkdir(parents=True, exist_ok=True)
    rows = []
    for meta in COMPANIES:
        row = frame.loc[meta[0]]
        if isinstance(row, pd.DataFrame):
            row = row.iloc[0]
        name = row["name_25"]
        text = frontmatter(meta, row) + "\n" + body(meta, row)
        (COMPANY_DIR / f"{name}.md").write_text(text, encoding="utf-8")
        rows.append((meta, row))
    return rows


def write_csv(rows):
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    records = []
    for meta, row in rows:
        records.append({
            "code": meta[0],
            "name": row["name_25"],
            "tier": meta[1],
            "moat": meta[2],
            "industry": row["ind_25"],
            "rev_2023_yi": round(yi(row["rev_23"]), 2),
            "rev_2024_yi": round(yi(row["rev_24"]), 2),
            "rev_2025_yi": round(yi(row["rev_25"]), 2),
            "np_2023_yi": round(yi(row["np_23"]), 2),
            "np_2024_yi": round(yi(row["np_24"]), 2),
            "np_2025_yi": round(yi(row["np_25"]), 2),
            "roe_2023": None if pd.isna(row["roe_23"]) else round(float(row["roe_23"]), 2),
            "roe_2024": None if pd.isna(row["roe_24"]) else round(float(row["roe_24"]), 2),
            "roe_2025": None if pd.isna(row["roe_25"]) else round(float(row["roe_25"]), 2),
            "gm_2023": None if pd.isna(row["gm_23"]) else round(float(row["gm_23"]), 2),
            "gm_2024": None if pd.isna(row["gm_24"]) else round(float(row["gm_24"]), 2),
            "gm_2025": None if pd.isna(row["gm_25"]) else round(float(row["gm_25"]), 2),
        })
    out = DATA_DIR / "护城河50_2023-2025业绩快照.csv"
    pd.DataFrame(records).to_csv(out, index=False)
    return out


