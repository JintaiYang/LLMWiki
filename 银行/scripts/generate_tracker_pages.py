# ─── Main ────────────────────────────────────────────────

def main() -> int:
    print("Loading bank universe...")
    banks = load_universe()
    focus_banks = [b for b in banks if b.get("focus18")]

    # Ensure directories exist
    TRACKER_DIR.mkdir(parents=True, exist_ok=True)
    RISK_DIR.mkdir(parents=True, exist_ok=True)
    VERIFY_DIR.mkdir(parents=True, exist_ok=True)
    DECISION_DIR.mkdir(parents=True, exist_ok=True)

    count = 0

    # ── 12_跟踪器 (7 pages) ──
    pages = [
        ("宏观与政策跟踪器", generate_macro_policy_tracker),
        ("息差与收入跟踪器", generate_nim_income_tracker),
        ("资产质量跟踪器", generate_asset_quality_tracker),
        ("资本与分红跟踪器", generate_capital_dividend_tracker),
        ("催化剂日历", generate_catalyst_calendar),
    ]
    for name, gen in pages:
        path = TRACKER_DIR / f"{name}.md"
        with open(path, "w", encoding="utf-8") as f:
            f.write(gen())
        count += 1
        print(f"  Created tracker: {name}")

    # Universe comparison table
    path = TRACKER_DIR / "全量银行核心指标比较表.md"
    with open(path, "w", encoding="utf-8") as f:
        f.write(generate_universe_comparison_table(banks))
    count += 1
    print("  Created tracker: 全量银行核心指标比较表")

    # A/H comparison table
    path = TRACKER_DIR / "A-H估值对照表.md"
    with open(path, "w", encoding="utf-8") as f:
        f.write(generate_ah_comparison_table(banks))
    count += 1
    print("  Created tracker: A-H估值对照表")

    # ── 14_风险 (1 industry + 18 banks = 19 pages) ──
    path = RISK_DIR / "银行业风险地图.md"
    with open(path, "w", encoding="utf-8") as f:
        f.write(generate_industry_risk_map())
    count += 1
    print("  Created risk: 银行业风险地图")

    for bank in focus_banks:
        name = bank["name"]
        path = RISK_DIR / f"{name} 风险档案.md"
        with open(path, "w", encoding="utf-8") as f:
            f.write(generate_bank_risk_page(name))
        count += 1
    print(f"  Created {len(focus_banks)} bank risk pages")

    # ── 08_验证与证据 (1 page) ──
    path = VERIFY_DIR / "验证日志.md"
    with open(path, "w", encoding="utf-8") as f:
        f.write(generate_verification_log())
    count += 1
    print("  Created verification: 验证日志")

    # ── 20_决策与复盘 (2 pages) ──
    dec_pages = [
        ("判断变更日志", generate_judgment_change_log),
        ("研究备忘录", generate_research_memo),
    ]
    for name, gen in dec_pages:
        path = DECISION_DIR / f"{name}.md"
        with open(path, "w", encoding="utf-8") as f:
            f.write(gen())
        count += 1
        print(f"  Created decision: {name}")

    tracker_count = 7
    risk_count = 1 + len(focus_banks)
    verify_count = 1
    decision_count = 2

    print(f"\n✅ Generated {count} pages total:")
    print(f"   12_跟踪器: {tracker_count} pages")
    print(f"   14_风险:   {risk_count} pages")
    print(f"   08_验证与证据: {verify_count} page")
    print(f"   20_决策与复盘: {decision_count} pages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())