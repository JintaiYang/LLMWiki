def load_universe() -> List[Dict[str, Any]]:
    path = DATA_BASE / "数据字典与运行记录" / "a_share_banks_universe.json"
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)
    return data["banks"]


