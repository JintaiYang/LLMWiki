"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { spawn } = require("node:child_process");
const { chromium } = require("playwright");
const output = process.env.LIQUOR_SCREENSHOTS || "/tmp/liquor-knowledge-qa";
async function main() {
  const folder = fs.mkdtempSync(path.join(os.tmpdir(), "liquor-knowledge-"));
  const snapshot = path.join(folder, "knowledge.json");
  fs.copyFileSync(path.join(__dirname, "../dashboard/knowledge.json"), snapshot);
  const seedCount = JSON.parse(fs.readFileSync(snapshot)).entries.length;
  const server = spawn("python3", [path.join(__dirname, "dashboard_server.py"), "--port", "0"], { env: { ...process.env, LIQUOR_KNOWLEDGE_FILE: snapshot }, stdio: ["ignore", "pipe", "ignore"] });
  let browser;
  try {
    const base = await new Promise((resolve, reject) => {
      const timer = setTimeout(() => reject(new Error("Test server did not start")), 10000);
      server.once("exit", (code) => { clearTimeout(timer); reject(new Error("Test server exited " + code)); });
      server.stdout.on("data", (chunk) => { const url = chunk.toString().match(/http:\/\/127\.0\.0\.1:\d+\//); if (url) { clearTimeout(timer); resolve(url[0]); } });
    });
    fs.mkdirSync(output, { recursive: true });
    browser = await chromium.launch({ headless: true, ...(process.env.LIQUOR_CHROME_PATH ? { executablePath: process.env.LIQUOR_CHROME_PATH } : {}) });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
    const errors = []; page.on("pageerror", (e) => errors.push(e.message));
    const go = async (url) => {
      await page.goto(base + url); await page.waitForFunction(() => window.__knowledgeReady === true);
      await page.addStyleTag({ content: "html { scroll-behavior: auto !important; }" });
      await page.evaluate(() => scrollTo(0, 0));
    };
    const countReportLinks = () => page.locator(".knowledge-item").evaluateAll((nodes) => nodes.filter((n) => !n.innerText.includes("通用口径")).length);
    await go("knowledge.html?company=600519&metric=cfi&period=2025-12-31#moutai-2025-interbank-certificates");
    assert.match(await page.locator("#knowledge-article h2").innerText(), /同业存单/);
    assert.equal(await countReportLinks(), 2);
    assert.match(await page.locator(".knowledge-context").innerText(), /2023年年报、2024年年报/);
    assert.equal((await page.request.get(base + "api/knowledge/source/moutai-2025")).headers()["content-type"], "application/pdf");
    await page.screenshot({ path: output + "/desktop.png", fullPage: true });
    await page.locator("#knowledge-period").selectOption("2024-12-31");
    assert.equal(await countReportLinks(), 0, "Historical references must not masquerade as current-period interpretation");
    await page.locator("#knowledge-period").selectOption("2026-06-30");
    assert.equal(await countReportLinks(), 0);
    await page.locator("#knowledge-company").selectOption("000858");
    assert.equal(await countReportLinks(), 0, "Company isolation");
    await page.locator("#knowledge-kind").selectOption("report");
    assert.match(await page.locator("#knowledge-list").innerText(), /没有匹配/);
    await page.locator("#knowledge-reset").click();
    assert.equal(await page.locator(".knowledge-item").count(), seedCount);
    await page.locator("#knowledge-query").fill("同业存单");
    assert(await page.locator(".knowledge-item").count() > 0);
    await page.locator("#knowledge-query").fill("不存在的问题123");
    assert.equal(await page.locator(".knowledge-item").count(), 0);
    await page.locator("#knowledge-reset").click();
    await page.locator("#knowledge-new").click();
    const form = page.locator("#knowledge-form");
    await form.locator('[name="title"]').fill("测试：2026中报投资现金流<script>window.bad=1</script>");
    await form.locator('[name="company"]').selectOption("600519");
    await form.locator('[name="kind"]').selectOption("report");
    await form.locator('[name="metrics"][value="cfi"]').check();
    await form.locator('[name="summary"]').fill("本期测试结论");
    await form.locator('[name="answer"]').fill("本期测试说明\n\n财务周期独立归档。");
    await page.locator("#knowledge-save").click();
    assert.match(await page.locator("#knowledge-save-status").innerText(), /必须选择适用报告期/);
    await form.locator('[data-add-period="periods"]').selectOption("2026-06-30");
    await page.locator("#knowledge-save").click();
    await page.waitForFunction(() => !document.querySelector(".knowledge-dialog"));
    assert.match(await page.locator("#knowledge-article h2").innerText(), /<script>/);
    assert.equal(await page.evaluate(() => window.bad), undefined);
    await page.reload(); await page.waitForFunction(() => window.__knowledgeReady === true);
    assert.match(await page.locator("#knowledge-article .knowledge-summary").innerText(), /本期测试结论/);
    const id = new URL(page.url()).hash.slice(1);
    await page.locator("#knowledge-edit").click();
    await page.locator('#knowledge-form [name="summary"]').fill("更新后的测试结论");
    await page.locator("#knowledge-save").click();
    await page.waitForFunction(() => !document.querySelector(".knowledge-dialog"));
    assert.match(await page.locator("#knowledge-article").innerText(), /版本 2/);
    const onDisk = JSON.parse(fs.readFileSync(snapshot));
    const changed = onDisk.entries.find((e) => e.id === id);
    assert.equal(changed.history[0].summary, "本期测试结论");
    assert.equal(changed.periods[0], "2026-06-30");
    const downloadPromise = page.waitForEvent("download"); await page.locator("#knowledge-export").click();
    const exported = JSON.parse(fs.readFileSync(await (await downloadPromise).path()));
    assert.equal(exported.entries.find((e) => e.id === id).summary, "更新后的测试结论");
    await page.locator("#knowledge-edit").click();
    await page.locator('#knowledge-form [name="summary"]').fill("不应覆盖的旧窗口修改");
    const remote = await (await page.request.get(base + "api/knowledge")).json();
    const competing = { ...remote.entries.find((e) => e.id === id), summary: "另一个窗口已保存" };
    assert.equal((await page.request.post(base + "api/knowledge", { data: { entry: competing, expected_revision: remote.revision } })).status(), 200);
    await page.locator("#knowledge-save").click();
    await page.waitForFunction(() => document.getElementById("knowledge-save-status").textContent.includes("其他窗口"));
    assert.equal(await page.locator('#knowledge-form [name="summary"]').inputValue(), "不应覆盖的旧窗口修改");
    assert.equal(JSON.parse(fs.readFileSync(snapshot)).entries.find((e) => e.id === id).summary, "另一个窗口已保存");
    page.once("dialog", (dialog) => dialog.accept()); await page.locator("dialog [data-close]").first().click();
    const forbidden = await page.request.post(base + "api/knowledge", { headers: { Origin: "https://example.com" }, data: { entry: competing, expected_revision: remote.revision + 1 } });
    assert.equal(forbidden.status(), 403);
    await page.goto(base + "stock.html?code=600519&report=2025&metrics=cash#stock-metric-cfi");
    await page.waitForFunction(() => window.__liquorReady === true);
    assert.equal(await page.locator(".metric-knowledge-notes").count(), 0, "Charts must not repeat knowledge lists");
    const metricLink = page.locator('[data-metric-row="cfi"] .metric-knowledge-link');
    assert.match(await metricLink.getAttribute("href"), /period=2025-12-31/);
    await page.locator("#metric-period").selectOption("2024");
    assert.match(await metricLink.getAttribute("href"), /period=2024-12-31/);
    await page.locator("#metric-period").selectOption("2026-06-30");
    const contextPack = JSON.parse(fs.readFileSync(snapshot));
    const relatedCount = require("../dashboard/knowledge-core.js").related(contextPack, "600519", "cfi", "2026-06-30").length;
    assert.match(await metricLink.getAttribute("aria-label"), new RegExp(relatedCount + "条"), "Compact entry reflects persisted content");
    await page.locator('[data-metric-row="cfi"] .metric-knowledge-link').click();
    await page.waitForFunction(() => window.__knowledgeReady === true);
    assert.equal(await page.locator("#knowledge-period").inputValue(), "2026-06-30");
    assert.equal(await page.locator("#knowledge-metric").inputValue(), "cfi");
    for (const width of [768, 390, 320]) {
      await page.setViewportSize({ width, height: 844 });
      await go("knowledge.html?company=600519&metric=cfi&period=2025-12-31#moutai-2025-interbank-certificates");
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), "No overflow at " + width);
      await page.screenshot({ path: output + `/knowledge-${width}.png`, fullPage: true });
      await page.locator("#knowledge-edit").click();
      await page.locator('#knowledge-form [name="answer"]').scrollIntoViewIfNeeded();
      assert(await page.locator('#knowledge-form [name="answer"]').isVisible());
      await page.screenshot({ path: output + `/editor-${width}.png` });
      await page.locator("dialog [data-close]").first().click();
    }
    await page.route("**/api/knowledge", (route) => route.fulfill({ status: 404, body: "missing" }));
    await go("knowledge.html");
    assert(await page.locator("#knowledge-new").isDisabled());
    assert.match(await page.locator("#knowledge-status").innerText(), /只读/);
    assert.deepEqual(errors, []);
    console.log("Knowledge: company/report isolation, search, source PDFs, create/edit durability, revision history, export, conflict protection, injection escaping, stock links, mobile layouts, and read-only fallback OK");
  } finally {
    if (browser) await browser.close();
    server.kill("SIGTERM");
    await new Promise((resolve) => { if (server.exitCode !== null || server.signalCode) resolve(); else server.once("exit", resolve); });
    fs.rmSync(folder, { recursive: true, force: true });
  }
}
main().catch((error) => { console.error(error); process.exitCode = 1; });
