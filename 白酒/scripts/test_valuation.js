"use strict";
const assert = require("node:assert/strict");
const { calculate, yearsBefore, observations } = require("../dashboard/valuation.js");
const { number, normalize } = require("./fetch_valuation_history.js");
const rows = Array.from({ length: 241 }, (_, i) => ({ date: `${2000 + Math.floor(i / 12)}-${String(i % 12 + 1).padStart(2, "0")}-01`, pe: i + 1, pb: 10 }));
const result = calculate(rows, "pe");
assert.equal(result[59].mean, null);
assert.equal(result[60].count5, 60);
assert.equal(result[60].mean, 31.5);
assert.equal(result[119].percentile10, null);
assert.equal(result[120].count10, 120);
assert.equal(result[120].percentile10, 100 * 119.5 / 120);
assert.equal(result.at(-1).count5, 60);
assert.equal(result.at(-1).mean, 211.5);
assert(Math.abs(result.at(-1).std - Math.sqrt((60 ** 2 - 1) / 12)) < 1e-10);
assert.equal(calculate(rows, "pb").at(-1).percentile5, 50);
assert.equal(calculate(rows, "pb").at(-1).std, 0);
assert.deepEqual(calculate(rows.slice(0, 200), "pe"), result.slice(0, 200), "No future observations affect historical statistics");
const missing = structuredClone(rows);
missing.at(-1).pe = -1;
missing.at(-2).pe = 0;
missing.at(-3).pe = null;
const last = calculate(missing, "pe").at(-1);
assert.equal(last.value, null);
assert.equal(last.percentile5, null);
assert.equal(last.count5, 57);
assert.equal(last.mean, 210);
assert.equal(yearsBefore("2024-02-29", 5), "2019-02-28");
assert.deepEqual(observations([{ date: "2024-01-01", pe: 2 }, { date: "2024-01-16", pe: 3 }, { date: "2024-02-01", pe: -1 }], "pe", "long").map((r) => r.pe), [3, -1]);
assert.equal(number(""), null);
assert.equal(number(null), null);
assert.equal(number("--"), null);
assert.equal(number("-2"), -2);
assert.throws(() => normalize([{ date: "2024-01-01", pe: 2 }, { date: "2024-01-01", pe: 3 }]), /重复/);
assert.throws(() => normalize([{ date: "2024-02-30", pe: 2 }]), /日期/);
console.log("Valuation calendar windows, midrank percentiles, population standard deviation, loss gaps, sampling, and no look-ahead OK");
